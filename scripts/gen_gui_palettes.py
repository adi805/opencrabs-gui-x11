#!/usr/bin/env python3
"""Generate GUI palettes from the TUI theme catalog.

The GUI draws a hardcoded four-theme palette (orgn/light/custom/auto) while the
TUI ships 31 themes in `src/tui/theme_catalog/pack/*.toml`. This script projects
each pack file onto the twenty fields of `config::gui_theme::Palette` so the GUI
can offer the same catalog.

Role mapping is fixed and total: every source key below exists in all 31 pack
files, so a missing key is an error rather than a silent fallback.

Outputs:
  assets/gui_themes/<name>.toml         20-field palette, embedded in the binary
  src/config/gui_palettes_builtin.rs    include_str! table for those files

Run `--check` in CI to prove the committed outputs match the pack source.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK_DIR = ROOT / "src" / "tui" / "theme_catalog" / "pack"
OUT_DIR = ROOT / "assets" / "gui_themes"
BUILTIN_RS = ROOT / "src" / "config" / "gui_palettes_builtin.rs"

# GUI Palette field -> TUI pack role. Order matches the Rust struct so the
# generated TOML reads like the const it replaces.
ROLE_MAP: list[tuple[str, str]] = [
    ("bg", "background"),
    ("panel", "surface_panel"),
    ("panel_hi", "surface_code_alt"),
    ("track", "surface_code"),
    ("text", "text_primary"),
    ("text_strong", "accent_soft"),
    ("text_normal", "text_secondary"),
    ("text_muted", "text_muted"),
    ("text_title", "text_dim"),
    ("text_faint", "gray_dim"),
    ("text_hint", "gray_muted"),
    ("green", "success"),
    ("blue", "blue_steel"),
    ("amber", "warning"),
    ("accent", "accent"),
    ("teal", "accent_teal"),
    ("red", "error"),
    ("warn", "warning_muted"),
    ("selection", "selection_bg"),
]

# `focus` is not taken from the pack: the window derives it from the accent so
# the ring and the accent can never disagree. Same formula as gui_theme::mix.
FOCUS_NUM, FOCUS_DEN = 55, 100


def parse_hex(value: str) -> int:
    body = value.strip().lstrip("#")
    if len(body) != 6:
        raise ValueError(f"not a #RRGGBB colour: {value!r}")
    return int(body, 16)


def mix(base: int, over: int, num: int, den: int) -> int:
    """Integer channel mix, bit-identical to gui_theme::mix."""

    def channel(b: int, o: int) -> int:
        return ((b * (den - num) + o * num) // den) & 0xFF

    return (
        (channel((base >> 16) & 0xFF, (over >> 16) & 0xFF) << 16)
        | (channel((base >> 8) & 0xFF, (over >> 8) & 0xFF) << 8)
        | channel(base & 0xFF, over & 0xFF)
    )


def build_palette(pack_path: Path) -> tuple[str, dict[str, str]]:
    data = tomllib.loads(pack_path.read_text(encoding="utf-8"))
    name = str(data.get("name") or pack_path.stem)
    palette: dict[str, str] = {}
    missing: list[str] = []
    for field, role in ROLE_MAP:
        raw = data.get(role)
        if not isinstance(raw, str) or not raw.strip().startswith("#"):
            missing.append(f"{role} ({field})")
            continue
        palette[field] = f"#{parse_hex(raw):06x}"
    if missing:
        raise SystemExit(f"{pack_path.name}: missing roles: {', '.join(missing)}")
    accent = parse_hex(palette["accent"])
    palette["focus"] = f"#{mix(parse_hex(palette['bg']), accent, FOCUS_NUM, FOCUS_DEN):06x}"
    return name, palette


HEADER = """# GUI palette, generated from the TUI theme catalog by
# scripts/gen_gui_palettes.py. Do not hand-edit: edit the pack file instead.
# Twenty fields, one per config::gui_theme::Palette member.
"""


def render_toml(slug: str, palette: dict[str, str]) -> str:
    lines = [HEADER, f'name = "{slug}"']
    for field, _role in ROLE_MAP:
        lines.append(f'{field} = "{palette[field]}"')
    lines.append(f'focus = "{palette["focus"]}"')
    return "\n".join(lines) + "\n"


def render_builtin(pairs: list[tuple[str, str]]) -> str:
    # Emit the shape `cargo fmt` produces, so a generated file never fails the
    # `fmt --check` gate: rustfmt's default heuristics keep a tuple on one line
    # only up to `fn_call_width` (60 columns), so anything longer is written as
    # the wrapped block it would otherwise rewrite.
    lines: list[str] = []
    for slug, _name in pairs:
        tuple_src = f'("{slug}", include_str!("../../assets/gui_themes/{slug}.toml")),'
        if len(tuple_src) <= 60:
            lines.append("    " + tuple_src)
        else:
            lines.append(
                "    (\n"
                f'        "{slug}",\n'
                f'        include_str!("../../assets/gui_themes/{slug}.toml"),\n'
                "    ),"
            )
    rows = "\n".join(lines)
    return (
        "// @generated by scripts/gen_gui_palettes.py — do not edit by hand.\n"
        "//\n"
        "// The TUI theme catalog, projected onto the GUI palette. Embedded so a\n"
        "// fresh install offers the whole catalog with no files on disk; a file in\n"
        "// `~/.opencrabs/gui_themes/` of the same name overrides its entry.\n"
        "\n"
        '/// (slug, palette TOML) for every theme shipped with the binary.\n'
        "pub const BUILTIN: &[(&str, &str)] = &[\n" + rows + "\n];\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify committed outputs are current; write nothing",
    )
    args = parser.parse_args()

    pack_files = sorted(PACK_DIR.glob("*.toml"))
    if not pack_files:
        raise SystemExit(f"no pack files under {PACK_DIR}")
    readme = PACK_DIR / "README.md"
    if readme.exists():
        pack_files = [p for p in pack_files if p.name.upper() != "README.TOML"]

    pairs: list[tuple[str, str]] = []
    rendered: dict[str, str] = {}
    for path in pack_files:
        name, palette = build_palette(path)
        slug = path.stem
        rendered[slug] = render_toml(slug, palette)
        pairs.append((slug, name))

    stale: list[str] = []
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for slug, body in rendered.items():
        target = OUT_DIR / f"{slug}.toml"
        if target.exists() and target.read_text(encoding="utf-8") == body:
            continue
        stale.append(f"assets/gui_themes/{slug}.toml")
        if not args.check:
            target.write_text(body, encoding="utf-8")

    builtin = render_builtin(pairs)
    if not BUILTIN_RS.exists() or BUILTIN_RS.read_text(encoding="utf-8") != builtin:
        stale.append("src/config/gui_palettes_builtin.rs")
        if not args.check:
            BUILTIN_RS.write_text(builtin, encoding="utf-8")

    # Files left over from a theme that was removed upstream.
    for old in OUT_DIR.glob("*.toml"):
        if old.stem not in rendered:
            stale.append(f"assets/gui_themes/{old.name} (orphan)")
            if not args.check:
                old.unlink()

    if args.check:
        if stale:
            print("stale generated palettes:\n  " + "\n  ".join(stale))
            return 1
        print(f"{len(rendered)} palettes match the pack source")
        return 0

    print(f"generated {len(rendered)} palettes into {OUT_DIR.relative_to(ROOT)}")
    if stale:
        print("updated: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    sys.exit(main())
